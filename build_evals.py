def utility(cmd):
    words = cmd.split()
    return words[1] if words[0] == "sudo" and len(words) > 1 else words[0]


def mc_item(query, gold, distractors, rng):
    choices = [gold] + distractors
    rng.shuffle(choices)
    return dict(query=query, choices=choices, gold=choices.index(gold))


def command_items(rows, rng):
    """Gold command + 3 commands from other items: 2 with the same utility when possible, the rest random."""
    commands = sorted({cmd for _, cmd, _ in rows})
    by_utility = defaultdict(list)
    for cmd in commands:
        by_utility[utility(cmd)].append(cmd)
    items = []
    for nl, cmd, correct in rows:
        same = [c for c in by_utility[utility(cmd)] if c not in correct]
        distractors = rng.sample(same, min(2, len(same)))
        others = [c for c in commands if c not in correct and c not in distractors]
        distractors += rng.sample(others, N_CHOICES - 1 - len(distractors))
        items.append(mc_item(f"# {nl}\n$", cmd, distractors, rng))
    return items


