SHELL_GENERATORS = [sh_lines, sh_grep, sh_dupes, sh_numbers, sh_csv, sh_misc, sh_files]


def run_shell(files, setup, command):
    """Runs the setup and then the command in a fresh directory; returns the command's stdout (None if it failed)."""
    with tempfile.TemporaryDirectory() as tmp:
        for name, content in files.items():
            with open(os.path.join(tmp, name), "w") as f:
                f.write(content)
        script = "".join(f"{cmd} > /dev/null\n" for cmd in setup) + command
        env = dict(PATH=os.environ["PATH"], LC_ALL="C")
        r = subprocess.run(["bash", "-c", script], cwd=tmp, capture_output=True, text=True, env=env, timeout=10)
        return r.stdout.rstrip("\n") if r.returncode == 0 and not r.stderr else None


def shell_item(rng):
    files, setup, options = rng.choice(SHELL_GENERATORS)(rng)
    shown = "".join(f"$ {cmd}\n" + (out + "\n" if (out := run_shell(files, setup[:i], cmd)) else "")
                    for i, cmd in enumerate(setup))
    outputs = [run_shell(files, setup, cmd) for cmd in options]
    return f"{shown}$ {options[0]}", outputs[0], outputs[1:]


