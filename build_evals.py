PY_EXPR_GENERATORS = [py_list, py_str, py_words, py_numbers, py_dict]


def run_python(code, expr=None):
    """Runs code and returns its stdout, or the repr of expr evaluated afterwards (None on an exception)."""
    out, scope = io.StringIO(), {}
    try:
        with contextlib.redirect_stdout(out):
            exec(code, scope)
            return repr(eval(expr, scope)) if expr else out.getvalue().rstrip("\n")
    except Exception:
        return None


def py_expr_item(rng):
    setup, options = rng.choice(PY_EXPR_GENERATORS)(rng)
    shown = "".join(f">>> {line}\n" for line in setup)
    outputs = [run_python("\n".join(setup), expr) for expr in options]
    return f"{shown}>>> {options[0]}", outputs[0], outputs[1:]


