def in_text(s, text):
    return re.search(rf"(?<!\w){re.escape(s)}(?!\w)", text) is not None


def output_items(make_item, n, rng):
    """n multiple choice items (distinct queries) from make_item(rng) -> (query, gold output, mistake outputs).
    Distractors are distinct mistake outputs, topped up with nearby numbers when the answer is a number. Unless the
    answer itself appears in the prompt, distractors that do are dropped: small models prefer copying (e.g. `cat f`
    for `sort f`), which would push them well below chance."""
    items, seen = [], set()
    while len(items) < n:
        query, gold, mistakes = make_item(rng)
        if not gold or query in seen:
            continue
        candidates = list(dict.fromkeys(m for m in mistakes if m and m != gold))
        rng.shuffle(candidates)
        if re.fullmatch(r"-?\d+", gold):
            nearby = [str(int(gold) + d) for d in rng.sample([-3, -2, -1, 1, 2, 3, 10], 7)]
            candidates += [c for c in nearby if c not in candidates and c != gold]
        if not in_text(gold, query):
            candidates = [c for c in candidates if not in_text(c, query)]
        if len(candidates) >= N_CHOICES - 1:
            seen.add(query)
            items.append(mc_item(query, gold, candidates[:N_CHOICES - 1], rng))
    return items


