def nl2sh_test():
    """Test splits of NL2SH-ALFA and nl2bash as {name: [(task, command, all correct commands for the task)]}."""
    with open(hf_file("westenfelder/NL2SH-ALFA", "test.csv")) as f:
        alfa = [(r["nl"].strip(), r["bash"].strip(), r["bash2"].strip()) for r in csv.DictReader(f)]
    nl2bash = pq.read_table(hf_file("jiacheng-ye/nl2bash", "default/test/0000.parquet", "refs/convert/parquet"))
    nl2bash = [(r["nl"].strip(), r["bash"].strip()) for r in nl2bash.to_pylist()]
    sets = {"nl2sh_alfa": alfa, "nl2bash": nl2bash}
    correct = defaultdict(set)  # the same task can appear more than once, with different commands
    for rows in sets.values():
        for nl, *cmds in rows:
            correct[nl].update(c for c in cmds if c)
    return {name: [(nl, cmds[0], correct[nl]) for nl, *cmds in rows] for name, rows in sets.items()}


def shell_texts():
    """Every (task, command) pair of both test sets, including NL2SH-ALFA's second reference command."""
    with open(hf_file("westenfelder/NL2SH-ALFA", "test.csv")) as f:
        pairs = [(r["nl"].strip(), r[k].strip()) for r in csv.DictReader(f) for k in ("bash", "bash2") if r[k].strip()]
    pairs += [(nl, cmd) for nl, cmd, _ in nl2sh_test()["nl2bash"]]
    return list(dict.fromkeys(pairs))  # dedup, keep order


def man_texts():
    texts = []
    env = dict(os.environ, MANWIDTH="80", LC_ALL="C")
    for name in dict.fromkeys(MAN_PAGES):
        cmd = f"man --nj --nh -P cat {name} | col -bx"
        r = subprocess.run(cmd, shell=True, capture_output=True, text=True, env=env)
        text = re.sub(r"\n{3,}", "\n\n", r.stdout)
        if r.returncode != 0 or len(text) < 500:
            continue
        if len(text) > MAN_PAGE_CHARS:
            text = text[:text.rindex("\n", 0, MAN_PAGE_CHARS) + 1]
        texts.append(text)
    return texts


def python_texts():
    humaneval = pq.read_table(hf_file("openai/openai_humaneval", "openai_humaneval/test-00000-of-00001.parquet"))
    texts = [r["prompt"] + r["canonical_solution"] for r in humaneval.to_pylist()]
    for split in ("prompt", "train", "validation", "test"):
        path = hf_file("google-research-datasets/mbpp", f"full/{split}-00000-of-00001.parquet")
        for r in pq.read_table(path).to_pylist():
            code = "\n".join(line.rstrip() for line in r["code"].replace("\r\n", "\n").split("\n")).strip()
            texts.append(f"# {r['text'].strip()}\n{code}\n\n" + "\n".join(r["test_list"]) + "\n")
    return texts


def build_bpb():
    if not os.path.exists(path := os.path.join(EVALS_DIR, "bpb", "shell.jsonl")):
        pairs = shell_texts()
        write_jsonl(path, [dict(context="", text=f"# {nl}\n$ {cmd}") for nl, cmd in pairs])
        cmd_only = [dict(context=f"# {nl}\n$", text=f" {cmd}") for nl, cmd in pairs]
        write_jsonl(path.replace("shell", "shell_cmd"), cmd_only)
    if not os.path.exists(path := os.path.join(EVALS_DIR, "bpb", "man.jsonl")):
        texts = man_texts()
        if len(texts) < 100:
            print(f"skipping the man page set: only {len(texts)} pages found (needs man-db)")
        else:
            write_jsonl(path, [dict(context="", text=t) for t in texts])
    if not os.path.exists(path := os.path.join(EVALS_DIR, "bpb", "python.jsonl")):
        write_jsonl(path, [dict(context="", text=t) for t in python_texts()])


