def weather_items(rng, n_weather=200, n_search=100, n_none=100):
    """Requests that need the weather tool (checked against the simulator: weather.summary), a lookup (search) or no
    tool, on the cities held out from training (scoring.eval_city)."""
    from scoring import eval_city
    cities = [c for c in WEATHER_CITIES if eval_city(c)]
    weather = [dict(kind="weather", field=f, day=day, city=c, question=t.format(city=c))
               for f, (day, ts) in WEATHER_TEMPLATES.items() for t in ts for c in cities]
    search = [dict(kind="search", city=c, question=t.format(city=c)) for t in SEARCH_TEMPLATES for c in cities]
    none = list({t.format(city=c): dict(kind="none", city=c, question=t.format(city=c))
                 for t in NO_TOOL_PROMPTS for c in cities}.values())
    return rng.sample(weather, n_weather) + rng.sample(search, n_search) + rng.sample(none, n_none)


